from pathlib import Path
from playwright.sync_api import sync_playwright
import json,os

root=Path(__file__).resolve().parent.parent
out=root/'docs/screenshots/motion';out.mkdir(parents=True,exist_ok=True)
url=os.environ.get('PORTFOLIO_TEST_URL','http://localhost:4173')
report={'checks':[],'errors':[]}
def check(name,value):
    if not value:raise AssertionError(name)
    report['checks'].append(name)

with sync_playwright() as p:
    browser=p.chromium.launch(executable_path=os.environ.get('BROWSER_EXECUTABLE','C:/Program Files (x86)/Microsoft/Edge/Application/msedge.exe'),headless=True)
    context=browser.new_context(viewport={'width':1440,'height':900},device_scale_factor=1)
    page=context.new_page();page.on('pageerror',lambda e:report['errors'].append(str(e)))
    page.goto(url,wait_until='networkidle')
    page.wait_for_function("document.querySelector('[data-explorer]').dataset.renderer==='three'",timeout=20000)
    page.wait_for_timeout(1300)
    check('real Three.js canvas mounted',page.locator('.system-drawing canvas').count()==1)
    page.screenshot(path=str(out/'three-hero-desktop.png'))
    page.locator('[data-source="1"]').click();page.locator('[data-stage="2"]').click()
    check('3D selection follows HTML source',page.locator('[data-explorer]').get_attribute('data-scene-source')=='1')
    check('3D selection follows HTML stage',page.locator('[data-explorer]').get_attribute('data-scene-stage')=='2')
    check('provenance returns to the selected source',page.locator('.provenance-return').get_attribute('d').endswith('V123H36'))
    page.locator('.motion-toggle').click()
    check('pause stops the renderer',page.locator('[data-explorer]').get_attribute('data-scene-paused')=='true')
    page.locator('[data-source="2"]').click()
    check('paused diagram still updates selection',page.locator('[data-explorer]').get_attribute('data-scene-source')=='2')
    page.locator('.motion-toggle').click()
    check('play resumes the renderer',page.locator('[data-explorer]').get_attribute('data-scene-paused')=='false')
    page.locator('[data-source="1"]').click();page.locator('[data-stage="2"]').click()
    page.locator('.system-drawing').hover(position={'x':480,'y':100});page.wait_for_timeout(500)
    page.screenshot(path=str(out/'three-decision-desktop.png'))
    page.locator('#project-synora').scroll_into_view_if_needed();page.wait_for_timeout(100)
    check('project entrance really animates',page.locator('#project-synora .project-art').evaluate('(e)=>e.getAnimations().some(a=>a.playState==="running")'))
    check('connectors draw in',page.locator('#project-synora .project-art svg path').evaluate_all('(paths)=>paths.some(p=>p.getAnimations().length>0)'))
    check('scroll progress advances',page.locator('.reading-progress').evaluate('(e)=>getComputedStyle(e).transform')!='matrix(0, 0, 0, 1, 0, 0)')
    page.wait_for_timeout(1600);page.screenshot(path=str(out/'project-desktop.png'))
    check('work index follows project',page.locator('[data-project-link="synora"]').get_attribute('aria-current')=='true')
    page.locator('#project-contextguard').scroll_into_view_if_needed();page.wait_for_timeout(1700)
    page.screenshot(path=str(out/'contextguard-desktop.png'))
    for width,height in [(320,740),(390,844),(768,1024),(1024,900),(1440,900),(1920,1080)]:
        page.set_viewport_size({'width':width,'height':height});page.wait_for_timeout(80)
        check(f'no motion overflow at {width}',not page.evaluate('document.documentElement.scrollWidth>innerWidth'))
    page.set_viewport_size({'width':1440,'height':900});page.goto(url,wait_until='networkidle')
    page.wait_for_function("document.querySelector('[data-explorer]').dataset.renderer==='three'")
    page.emulate_media(reduced_motion='reduce');page.wait_for_timeout(100)
    check('reduced motion disposes canvas',page.locator('.system-drawing canvas').count()==0)
    check('reduced motion restores semantic SVG',page.locator('.system-drawing>svg').evaluate('(e)=>getComputedStyle(e).opacity')=='1')
    check('reduced motion stops title animation',page.locator('.hero-line>span').first.evaluate('(e)=>getComputedStyle(e).animationName')=='none')
    page.set_viewport_size({'width':390,'height':844});page.emulate_media(reduced_motion='no-preference');page.goto(url,wait_until='networkidle');page.wait_for_timeout(1200)
    check('mobile uses lightweight SVG',page.locator('.system-drawing canvas').count()==0)
    check('mobile has visible moving flow',page.locator('.source-route.active path').evaluate('(e)=>getComputedStyle(e).animationName')=='evidence-flow')
    page.screenshot(path=str(out/'hero-mobile.png'))
    fallback=browser.new_context(viewport={'width':1440,'height':900})
    fallback.add_init_script("const original=HTMLCanvasElement.prototype.getContext;HTMLCanvasElement.prototype.getContext=function(type,...args){return /webgl/.test(type)?null:original.call(this,type,...args)}")
    static=fallback.new_page();static.on('pageerror',lambda e:report['errors'].append(str(e)));static.goto(url,wait_until='networkidle');static.wait_for_timeout(1400)
    check('WebGL failure keeps SVG visible',static.locator('.system-drawing>svg').evaluate('(e)=>getComputedStyle(e).opacity')=='1')
    static.locator('[data-stage="2"]').click();check('WebGL failure preserves controls',static.locator('[data-stage="2"]').get_attribute('aria-pressed')=='true')
    check('no runtime errors',not report['errors'])
    fallback.close();context.close();browser.close()
(root/'docs/motion-results.json').write_text(json.dumps(report,indent=2),encoding='utf-8')
print(json.dumps({'passed':len(report['checks']),'errors':report['errors']}))
